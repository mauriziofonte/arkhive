<?php

declare(strict_types=1);

namespace Mfonte\Arkhive\Services\Schedule;

/**
 * The cron variant: root gets /etc/cron.d lines (with the user field), anyone else lines for
 * `crontab -e`. Output goes to the --log-file; failures reach people through NOTIFY_ON.
 */
final class CronTable
{
    public const CRON_D = '/etc/cron.d/arkhive';
    public const PATH = 'PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin';

    public static function render(Schedule $schedule): string
    {
        $lines = "# Generated by arkhive schedule for {$schedule->config}\n"
            . ($schedule->root()
                ? '# Save as ' . self::CRON_D . " (root:root, mode 0644). Logs: {$schedule->logFile}\n"
                : "# Add to the crontab of {$schedule->user} with: crontab -e. Logs: {$schedule->logFile}\n")
            // cron starts jobs with PATH=/usr/bin:/bin, which misses /usr/local/bin
            . self::PATH . "\n";
        foreach (Job::cases() as $job) {
            [$hour, $minute] = $schedule->timeOf($job);
            $weekday = $job->weekday();
            $command = implode(' ', array_map(self::quote(...), [
                'nice', '-n', '10',
                ...$schedule->invocation,
                ...$schedule->arguments($job),
                '--log-file', $schedule->logFile,
            ]));
            $lines .= sprintf(
                "%d %d * * %s %s%s >/dev/null 2>&1\n",
                $minute,
                $hour,
                $weekday ?? '*',
                $schedule->root() ? 'root ' : '',
                $command,
            );
        }

        return $lines;
    }

    /**
     * One shell word; % is special to cron even inside quotes.
     */
    private static function quote(string $argument): string
    {
        $word = preg_match('/^[A-Za-z0-9_@%+=:,.\/-]+$/', $argument) === 1 ? $argument : escapeshellarg($argument);

        return str_replace('%', '\%', $word);
    }
}

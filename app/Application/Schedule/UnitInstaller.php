<?php

declare(strict_types=1);

namespace Mfonte\Arkhive\Application\Schedule;

use Mfonte\Arkhive\Domain\Schedule\SystemdUnits;
use Mfonte\Arkhive\Exceptions\IoException;
use Mfonte\Arkhive\Exceptions\RefusedException;

/**
 * Writes rendered unit files into a unit directory: each one atomically (temporary file, rename),
 * mode 0644, and never over a file that `arkhive schedule` did not generate.
 */
final class UnitInstaller
{
    /**
     * @param array<string, string> $units file name => content
     *
     * @return array<string, bool> path => whether it was written (false: already identical)
     *
     * @throws RefusedException the directory is missing, or a unit file there was not generated by ArkHive
     * @throws IoException      a unit file cannot be written
     */
    public static function install(array $units, string $directory): array
    {
        if (!is_dir($directory)) {
            throw new RefusedException("The unit directory {$directory} does not exist", hint: 'Is this host running systemd?');
        }
        $paths = [];
        foreach ($units as $name => $content) {
            $path = rtrim($directory, '/') . '/' . $name;
            $current = self::read($path);
            if ($current !== null && !str_starts_with($current, SystemdUnits::MARKER)) {
                throw new RefusedException("{$path} exists and was not generated by arkhive schedule: not overwriting it", hint: 'Move it away (or merge it by hand with: arkhive schedule --systemd), then install again');
            }
            $paths[$path] = $current !== $content;
        }
        foreach ($paths as $path => $changed) {
            if ($changed) {
                self::write($path, $units[basename($path)]);
            }
        }

        return $paths;
    }

    private static function read(string $path): ?string
    {
        if (!file_exists($path) && !is_link($path)) {
            return null;
        }
        $content = is_file($path) ? @file_get_contents($path) : false;
        if ($content === false) {
            throw new RefusedException("{$path} exists and is not a readable file: not overwriting it");
        }

        return $content;
    }

    private static function write(string $path, string $content): void
    {
        $temporary = dirname($path) . '/.' . basename($path) . '.' . bin2hex(random_bytes(4));
        $written = @file_put_contents($temporary, $content);
        if ($written !== strlen($content) || !@chmod($temporary, 0644) || !@rename($temporary, $path)) {
            @unlink($temporary);

            throw new IoException("Cannot write the unit file {$path}", hint: 'Run as root: the unit directory belongs to root');
        }
    }
}

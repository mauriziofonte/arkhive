<?php

declare(strict_types=1);

namespace Mfonte\Arkhive\Domain\Schedule;

/**
 * spec §11: a oneshot service and a timer per job, at low CPU and I/O priority, with a start
 * timeout. Under systemd ArkHive detects INVOCATION_ID and logs for journald.
 *
 * 2.1: the units are hardened (read-only system and homes, except the state and cache directories
 * systemd creates and the directories the jobs write), report their status (NotifyAccess=main),
 * and are ordered so that maintain and drill never start while a backup runs.
 */
final class SystemdUnits
{
    public const DIRECTORY = '/etc/systemd/system';

    /**
     * @return array<string, string> unit path => content
     */
    public static function render(Schedule $schedule): array
    {
        $units = [];
        foreach (Job::cases() as $job) {
            $name = self::DIRECTORY . "/arkhive-{$job->value}";
            $units["{$name}.service"] = self::service($schedule, $job);
            $units["{$name}.timer"] = self::timer($schedule, $job);
        }

        return $units;
    }

    /**
     * @return list<string>
     */
    public static function timers(): array
    {
        return array_map(static fn (Job $job): string => "arkhive-{$job->value}.timer", Job::cases());
    }

    private static function service(Schedule $schedule, Job $job): string
    {
        $command = implode(' ', array_map(self::quote(...), [...$schedule->invocation, ...$schedule->arguments($job)]));
        $after = implode(' ', ['network-online.target', ...array_map(static fn (Job $before): string => "arkhive-{$before->value}.service", $job->after())]);
        $writable = $schedule->writable === [] ? '' : 'ReadWritePaths=' . implode(' ', array_map(static fn (string $path): string => self::path('-' . $path), $schedule->writable)) . "\n";

        return self::header($schedule)
            . "[Unit]\n"
            . "Description={$job->description()}\n"
            . "Documentation=https://github.com/mauriziofonte/arkhive\n"
            . "Wants=network-online.target\n"
            . "After={$after}\n"
            . "\n"
            . "[Service]\n"
            . "Type=oneshot\n"
            // the unit status (systemctl status), more time while progress is made, watchdog pings
            . "NotifyAccess=main\n"
            // explicit even for root: systemd then sets HOME, where ssh finds its keys and known_hosts
            . "User={$schedule->user}\n"
            . "ExecStart={$command}\n"
            . "Nice=10\n"
            . "IOSchedulingClass=idle\n"
            . "CPUSchedulingPolicy=batch\n"
            . "TimeoutStartSec={$job->timeout()}\n"
            // /var/lib/arkhive (the outcome of each run) and /var/cache/arkhive (restic's cache), owned by User=
            . "StateDirectory=arkhive\n"
            . "CacheDirectory=arkhive\n"
            . "ProtectSystem=full\n"
            . "ProtectHome=read-only\n"
            . $writable
            . "PrivateTmp=true\n"
            . "NoNewPrivileges=true\n"
            . "ProtectKernelTunables=true\n"
            . "ProtectKernelModules=true\n"
            . "ProtectControlGroups=true\n"
            . "RestrictSUIDSGID=true\n"
            . "LockPersonality=true\n";
    }

    private static function timer(Schedule $schedule, Job $job): string
    {
        [$hour, $minute] = $schedule->timeOf($job);
        $every = $job->weekday() === null ? 'Daily' : 'Weekly';

        return self::header($schedule)
            . "[Unit]\n"
            . "Description={$every} {$job->description()}\n"
            . "\n"
            . "[Timer]\n"
            . sprintf("OnCalendar=%s*-*-* %02d:%02d:00\n", $job->calendarDay(), $hour, $minute)
            // hosts with the same --at do not all reach the repository server at once
            . "RandomizedDelaySec=10min\n"
            . "AccuracySec=1min\n"
            // a run missed while the machine was off starts at the next boot
            . "Persistent=true\n"
            . "\n"
            . "[Install]\n"
            . "WantedBy=timers.target\n";
    }

    private static function header(Schedule $schedule): string
    {
        return "# Generated by arkhive schedule for {$schedule->config}\n";
    }

    /**
     * One path of a list setting such as ReadWritePaths=: % escaped (specifiers are expanded there,
     * variables are not), double quotes when needed.
     */
    private static function path(string $path): string
    {
        $escaped = str_replace('%', '%%', $path);
        if (preg_match('/^[A-Za-z0-9_@%+=:,.\/-]+$/', $escaped) === 1) {
            return $escaped;
        }

        return '"' . str_replace(['\\', '"'], ['\\\\', '\\"'], $escaped) . '"';
    }

    /**
     * One ExecStart= argument: % and $ escaped for systemd, double quotes when needed.
     */
    private static function quote(string $argument): string
    {
        $escaped = str_replace(['%', '$'], ['%%', '$$'], $argument);
        if (preg_match('/^[A-Za-z0-9_@%+=:,.\/-]+$/', $escaped) === 1) {
            return $escaped;
        }

        return '"' . str_replace(['\\', '"'], ['\\\\', '\\"'], $escaped) . '"';
    }
}

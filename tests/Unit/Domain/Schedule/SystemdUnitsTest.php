<?php

declare(strict_types=1);

namespace Tests\Unit\Domain\Schedule;

use Mfonte\Arkhive\Domain\Schedule\Schedule;
use Mfonte\Arkhive\Domain\Schedule\SystemdUnits;
use PHPUnit\Framework\TestCase;

final class SystemdUnitsTest extends TestCase
{
    public function testTheBackupServiceAndTimer(): void
    {
        $units = SystemdUnits::render(new Schedule(['/usr/local/bin/arkhive'], '/etc/arkhive/config', 'root', 2, 30, '/var/log/arkhive.log'));

        self::assertSame([
            '/etc/systemd/system/arkhive-backup.service',
            '/etc/systemd/system/arkhive-backup.timer',
            '/etc/systemd/system/arkhive-maintain.service',
            '/etc/systemd/system/arkhive-maintain.timer',
            '/etc/systemd/system/arkhive-drill.service',
            '/etc/systemd/system/arkhive-drill.timer',
            '/etc/systemd/system/arkhive-failure@.service',
        ], array_keys($units));
        self::assertSame(
            "# Generated by arkhive schedule for /etc/arkhive/config\n"
            . "[Unit]\n"
            . "Description=ArkHive backup\n"
            . "Documentation=https://github.com/mauriziofonte/arkhive\n"
            . "Wants=network-online.target\n"
            . "After=network-online.target\n"
            . "OnFailure=arkhive-failure@%n.service\n"
            . "\n"
            . "[Service]\n"
            . "Type=oneshot\n"
            . "NotifyAccess=main\n"
            . "User=root\n"
            . "ExecStart=/usr/local/bin/arkhive backup --config /etc/arkhive/config\n"
            . "Nice=10\n"
            . "IOSchedulingClass=idle\n"
            . "CPUSchedulingPolicy=batch\n"
            . "TimeoutStartSec=6h\n"
            . "StateDirectory=arkhive\n"
            . "CacheDirectory=arkhive\n"
            . "ProtectSystem=full\n"
            . "ProtectHome=read-only\n"
            . "PrivateTmp=true\n"
            . "NoNewPrivileges=true\n"
            . "ProtectKernelTunables=true\n"
            . "ProtectKernelModules=true\n"
            . "ProtectControlGroups=true\n"
            . "RestrictSUIDSGID=true\n"
            . "LockPersonality=true\n",
            $units['/etc/systemd/system/arkhive-backup.service'],
        );
        self::assertSame(
            "# Generated by arkhive schedule for /etc/arkhive/config\n"
            . "[Unit]\n"
            . "Description=Daily ArkHive backup\n"
            . "\n"
            . "[Timer]\n"
            . "OnCalendar=*-*-* 02:30:00\n"
            . "RandomizedDelaySec=10min\n"
            . "AccuracySec=1min\n"
            . "Persistent=true\n"
            . "\n"
            . "[Install]\n"
            . "WantedBy=timers.target\n",
            $units['/etc/systemd/system/arkhive-backup.timer'],
        );
    }

    public function testTheFailureTemplateNotifiesAboutTheFailedUnit(): void
    {
        $units = SystemdUnits::render(new Schedule(['/usr/bin/php8.4', '/home/deploy/bin/arkhive.phar'], '/home/deploy/my config', 'deploy', 2, 30, '/var/log/arkhive.log'));

        self::assertSame(
            "# Generated by arkhive schedule for /home/deploy/my config\n"
            . "[Unit]\n"
            . "Description=ArkHive notification about the failed %i\n"
            . "Documentation=https://github.com/mauriziofonte/arkhive\n"
            . "After=network-online.target\n"
            . "\n"
            . "[Service]\n"
            . "Type=oneshot\n"
            . "User=root\n"
            . "ExecStart=/usr/bin/php8.4 /home/deploy/bin/arkhive.phar notify --failed-unit %i --config \"/home/deploy/my config\"\n"
            . "SuccessExitStatus=3\n"
            . "TimeoutStartSec=10min\n"
            . "PrivateTmp=true\n"
            . "NoNewPrivileges=true\n",
            $units['/etc/systemd/system/arkhive-failure@.service'],
            'as root, which reads the system journal, whoever the jobs run as',
        );
        foreach (['backup', 'maintain', 'drill'] as $job) {
            self::assertStringContainsString("OnFailure=arkhive-failure@%n.service\n", $units["/etc/systemd/system/arkhive-{$job}.service"]);
        }
    }

    public function testMaintainAndDrillAreWeeklyWithLongerAndShorterTimeouts(): void
    {
        $units = SystemdUnits::render(new Schedule(['/usr/local/bin/arkhive'], '/etc/arkhive/config', 'root', 22, 5, '/var/log/arkhive.log'));

        self::assertStringContainsString("OnCalendar=*-*-* 22:05:00\n", $units['/etc/systemd/system/arkhive-backup.timer']);
        self::assertStringContainsString("Description=Weekly ArkHive maintenance (retention, prune, check)\n", $units['/etc/systemd/system/arkhive-maintain.timer']);
        self::assertStringContainsString("OnCalendar=Sun *-*-* 01:05:00\n", $units['/etc/systemd/system/arkhive-maintain.timer']);
        self::assertStringContainsString("OnCalendar=Wed *-*-* 01:05:00\n", $units['/etc/systemd/system/arkhive-drill.timer']);
        self::assertStringContainsString("TimeoutStartSec=12h\n", $units['/etc/systemd/system/arkhive-maintain.service']);
        self::assertStringContainsString("TimeoutStartSec=3h\n", $units['/etc/systemd/system/arkhive-drill.service']);
        self::assertStringContainsString("After=network-online.target\n", $units['/etc/systemd/system/arkhive-backup.service']);
        self::assertStringContainsString("After=network-online.target arkhive-backup.service\n", $units['/etc/systemd/system/arkhive-maintain.service'], 'a maintain due with a backup waits for it');
        self::assertStringContainsString("After=network-online.target arkhive-backup.service arkhive-maintain.service\n", $units['/etc/systemd/system/arkhive-drill.service']);
        self::assertSame(['arkhive-backup.timer', 'arkhive-maintain.timer', 'arkhive-drill.timer'], SystemdUnits::timers());
    }

    public function testAnotherUserAndPhpWithThePhar(): void
    {
        $units = SystemdUnits::render(new Schedule(['/usr/bin/php8.4', '/home/deploy/bin/arkhive.phar'], '/home/deploy/.config/arkhive/config', 'deploy', 2, 30, '/home/deploy/.local/state/arkhive/arkhive.log'));

        self::assertStringContainsString("User=deploy\nExecStart=/usr/bin/php8.4 /home/deploy/bin/arkhive.phar backup --config /home/deploy/.config/arkhive/config\n", $units['/etc/systemd/system/arkhive-backup.service']);
    }

    public function testTheDirectoriesTheJobsWriteStayWritable(): void
    {
        $units = SystemdUnits::render(new Schedule(['/usr/local/bin/arkhive'], '/etc/arkhive/config', 'root', 2, 30, '/var/log/arkhive.log', ['/home/backup/dumps', '/srv/my repo/100%"x"']));

        // "-": a directory that does not exist yet does not stop the unit
        self::assertStringContainsString("ProtectHome=read-only\nReadWritePaths=-/home/backup/dumps \"-/srv/my repo/100%%\\\"x\\\"\"\nPrivateTmp=true\n", $units['/etc/systemd/system/arkhive-backup.service']);
        self::assertStringNotContainsString('ReadWritePaths', SystemdUnits::render(new Schedule(['/usr/local/bin/arkhive'], '/etc/arkhive/config', 'root', 2, 30, '/var/log/arkhive.log'))['/etc/systemd/system/arkhive-backup.service']);
    }

    public function testExecStartQuoting(): void
    {
        $units = SystemdUnits::render(new Schedule(['/opt/ark hive/arkhive'], '/etc/my "conf"/100%$HOME\\x', 'root', 2, 30, '/var/log/arkhive.log'));

        // % and $ are systemd specifiers and variables; spaces, quotes and backslashes need double quotes
        self::assertStringContainsString('ExecStart="/opt/ark hive/arkhive" backup --config "/etc/my \"conf\"/100%%$$HOME\\\\x"' . "\n", $units['/etc/systemd/system/arkhive-backup.service']);
        self::assertStringContainsString("# Generated by arkhive schedule for /etc/my \"conf\"/100%\$HOME\\x\n", $units['/etc/systemd/system/arkhive-backup.timer']);
        $plain = SystemdUnits::render(new Schedule(['/usr/local/bin/arkhive'], '/etc/arkhive/web_1@host+a=b:c,d.conf', 'root', 2, 30, '/var/log/arkhive.log'));
        self::assertStringContainsString("ExecStart=/usr/local/bin/arkhive backup --config /etc/arkhive/web_1@host+a=b:c,d.conf\n", $plain['/etc/systemd/system/arkhive-backup.service']);
    }
}

<?php

declare(strict_types=1);

namespace Tests\Unit\Application\Schedule;

use Mfonte\Arkhive\Application\Schedule\UnitInstaller;
use Mfonte\Arkhive\Exceptions\ArkhiveException;
use Mfonte\Arkhive\ExitCode;
use PHPUnit\Framework\TestCase;
use Tests\Support\TempDir;

final class UnitInstallerTest extends TestCase
{
    use TempDir;

    private const BACKUP = "# Generated by arkhive schedule for /etc/arkhive/config\n[Unit]\nDescription=ArkHive backup\n";

    public function testWritesNewUnitsAndSkipsIdenticalOnes(): void
    {
        $dir = $this->tempDir();
        $umask = umask(0077);
        try {
            self::assertSame(["{$dir}/arkhive-backup.service" => true, "{$dir}/arkhive-backup.timer" => true], UnitInstaller::install(['arkhive-backup.service' => self::BACKUP, 'arkhive-backup.timer' => "# Generated by arkhive schedule\n[Timer]\n"], $dir));
        } finally {
            umask($umask);
        }

        self::assertSame(self::BACKUP, file_get_contents("{$dir}/arkhive-backup.service"));
        self::assertSame(0644, fileperms("{$dir}/arkhive-backup.service") & 0777, 'readable by systemd whatever the umask');
        self::assertSame(['arkhive-backup.service', 'arkhive-backup.timer'], array_values(array_diff((array) scandir($dir), ['.', '..'])), 'no temporary file is left');

        $changed = str_replace('backup', 'backup now', self::BACKUP);
        self::assertSame(["{$dir}/arkhive-backup.service" => true, "{$dir}/arkhive-backup.timer" => false], UnitInstaller::install(['arkhive-backup.service' => $changed, 'arkhive-backup.timer' => "# Generated by arkhive schedule\n[Timer]\n"], $dir));
        self::assertSame($changed, file_get_contents("{$dir}/arkhive-backup.service"));
    }

    public function testNeverOverwritesAUnitItDidNotGenerate(): void
    {
        $dir = $this->tempDir();
        file_put_contents("{$dir}/arkhive-drill.timer", "[Timer]\nOnCalendar=daily\n");

        try {
            UnitInstaller::install(['arkhive-backup.service' => self::BACKUP, 'arkhive-drill.timer' => self::BACKUP], $dir);
            self::fail('expected a refusal');
        } catch (ArkhiveException $e) {
            self::assertSame(ExitCode::CANNOT_CREATE, $e->exitCode());
            self::assertSame("{$dir}/arkhive-drill.timer exists and was not generated by arkhive schedule: not overwriting it", $e->getMessage());
        }
        self::assertFileDoesNotExist("{$dir}/arkhive-backup.service", 'nothing is written when one unit is refused');
        self::assertSame("[Timer]\nOnCalendar=daily\n", file_get_contents("{$dir}/arkhive-drill.timer"));

        mkdir("{$dir}/arkhive-backup.service");
        try {
            UnitInstaller::install(['arkhive-backup.service' => self::BACKUP], $dir);
            self::fail('expected a refusal');
        } catch (ArkhiveException $e) {
            self::assertSame(ExitCode::CANNOT_CREATE, $e->exitCode());
            self::assertSame("{$dir}/arkhive-backup.service exists and is not a readable file: not overwriting it", $e->getMessage());
        }
    }

    public function testAMissingOrReadOnlyDirectory(): void
    {
        try {
            UnitInstaller::install(['arkhive-backup.service' => self::BACKUP], '/nonexistent/systemd/system');
            self::fail('expected a refusal');
        } catch (ArkhiveException $e) {
            self::assertSame(ExitCode::CANNOT_CREATE, $e->exitCode());
            self::assertSame('The unit directory /nonexistent/systemd/system does not exist', $e->getMessage());
        }

        if (posix_geteuid() === 0) {
            self::markTestSkipped('root writes into a read-only directory');
        }
        $dir = $this->tempDir();
        chmod($dir, 0555);
        try {
            UnitInstaller::install(['arkhive-backup.service' => self::BACKUP], $dir);
            self::fail('expected a failure');
        } catch (ArkhiveException $e) {
            self::assertSame(ExitCode::IO_ERROR, $e->exitCode());
            self::assertSame("Cannot write the unit file {$dir}/arkhive-backup.service", $e->getMessage());
        } finally {
            chmod($dir, 0755);
        }
    }
}

<?php

declare(strict_types=1);

namespace Tests\Feature;

use Illuminate\Support\Facades\Artisan;
use Mfonte\Arkhive\Application\Port\Prompter;
use Mfonte\Arkhive\Application\Port\ServiceUnits;
use Mfonte\Arkhive\Commands\ScheduleCommand;
use Mfonte\Arkhive\ExitCode;
use Tests\Support\Cli;
use Tests\Support\FakePrompter;
use Tests\Support\FakeServiceUnits;
use Tests\Support\TempDir;
use Tests\Support\WritesConfig;
use Tests\TestCase;

/**
 * spec §11 `arkhive schedule --systemd|--cron`: prints the units or lines for the current
 * configuration; --install writes them (root only), --status reads them back from systemd.
 */
final class ScheduleCommandTest extends TestCase
{
    use TempDir;
    use WritesConfig;

    private string $dir;

    private FakeServiceUnits $units;

    protected function setUp(): void
    {
        parent::setUp();
        $this->dir = $this->tempDir();
        ScheduleCommand::$invocation = ['/usr/local/bin/arkhive'];
        ScheduleCommand::$user = 'root';
        ScheduleCommand::$systemd = true;
        ScheduleCommand::$euid = 0;
        ScheduleCommand::$unitDirectory = $this->tempDir();
        $this->units = new FakeServiceUnits();
        $this->app->instance(ServiceUnits::class, $this->units);
    }

    protected function tearDown(): void
    {
        ScheduleCommand::$invocation = null;
        ScheduleCommand::$user = null;
        ScheduleCommand::$systemd = null;
        ScheduleCommand::$euid = null;
        ScheduleCommand::$unitDirectory = null;
        parent::tearDown();
    }

    public function testInstallWritesTheUnitsAndEnablesTheTimers(): void
    {
        $config = $this->writeConfig();
        $units = (string) ScheduleCommand::$unitDirectory;

        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => $config, '--install' => true, '--at' => '01:15']), $this->logOutput());

        self::assertSame('', Artisan::output(), 'nothing to save by hand');
        $files = array_values(array_diff((array) scandir($units), ['.', '..']));
        self::assertSame(['arkhive-backup.service', 'arkhive-backup.timer', 'arkhive-drill.service', 'arkhive-drill.timer', 'arkhive-failure@.service', 'arkhive-maintain.service', 'arkhive-maintain.timer'], $files);
        self::assertStringContainsString("OnCalendar=*-*-* 01:15:00\n", (string) file_get_contents("{$units}/arkhive-backup.timer"));
        self::assertStringContainsString("ExecStart=/usr/local/bin/arkhive backup --config {$config}\n", (string) file_get_contents("{$units}/arkhive-backup.service"));
        self::assertSame(0644, fileperms("{$units}/arkhive-backup.service") & 0777);
        self::assertSame(['daemon-reload', 'enable --now arkhive-backup.timer arkhive-maintain.timer arkhive-drill.timer'], $this->units->calls);
        self::assertStringContainsString("info Wrote {$units}/arkhive-backup.service", $this->logOutput());
        self::assertStringContainsString('success Enabled arkhive-backup.timer, arkhive-maintain.timer, arkhive-drill.timer: check them with arkhive schedule --status', $this->logOutput());

        // again, unchanged: nothing rewritten, systemd still reloaded and the timers enabled (idempotent)
        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => $config, '--install' => true, '--at' => '01:15']));
        self::assertStringContainsString("info Unchanged: {$units}/arkhive-backup.service", $this->logOutput());
        self::assertCount(4, $this->units->calls);
    }

    public function testInstallNeverOverwritesAForeignUnit(): void
    {
        $units = (string) ScheduleCommand::$unitDirectory;
        file_put_contents("{$units}/arkhive-backup.timer", "[Timer]\nOnCalendar=hourly\n");

        self::assertSame(ExitCode::CANNOT_CREATE, Artisan::call('schedule', ['--config' => $this->writeConfig(), '--install' => true]));

        self::assertStringContainsString("error {$units}/arkhive-backup.timer exists and was not generated by arkhive schedule: not overwriting it", $this->logOutput());
        self::assertSame("[Timer]\nOnCalendar=hourly\n", file_get_contents("{$units}/arkhive-backup.timer"));
        self::assertFileDoesNotExist("{$units}/arkhive-backup.service");
        self::assertSame([], $this->units->calls, 'systemd is not touched');
    }

    public function testInstallNeedsRootAndSystemd(): void
    {
        ScheduleCommand::$euid = 1000;
        self::assertSame(ExitCode::NO_PERMISSION, Artisan::call('schedule', ['--config' => $this->writeConfig(), '--install' => true]));
        self::assertStringContainsString('error arkhive schedule --install writes to ' . ScheduleCommand::$unitDirectory . ' and must run as root', $this->logOutput());
        self::assertSame([], $this->units->calls);

        ScheduleCommand::$euid = 0;
        self::assertSame(ExitCode::USAGE, Artisan::call('schedule', ['--config' => $this->writeConfig(), '--install' => true, '--cron' => true]));
        self::assertStringContainsString('error --install writes systemd units: it cannot be combined with --cron', $this->logOutput());
    }

    public function testStatusOfHealthyTimers(): void
    {
        foreach (['backup', 'maintain', 'drill'] as $job) {
            $this->units->properties["arkhive-{$job}.timer"] = ['LoadState' => 'loaded', 'UnitFileState' => 'enabled', 'ActiveState' => 'active', 'NextElapseUSecRealtime' => 'Thu 2026-10-15 02:30:00 UTC', 'LastTriggerUSec' => 'n/a'];
        }
        $this->units->properties['arkhive-backup.timer']['LastTriggerUSec'] = 'Wed 2026-10-14 02:31:12 UTC';
        $this->units->properties['arkhive-backup.service'] = ['Result' => 'success', 'ExecMainCode' => '1', 'ExecMainStatus' => '0', 'ExecMainStartTimestamp' => 'Wed 2026-10-14 02:31:12 UTC', 'ExecMainExitTimestamp' => 'Wed 2026-10-14 02:40:01 UTC'];

        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--status' => true]), $this->logOutput());

        self::assertSame(
            "JOB       TIMER    NEXT RUN                     LAST RUN                     LAST RESULT\n"
            . "backup    enabled  Thu 2026-10-15 02:30:00 UTC  Wed 2026-10-14 02:31:12 UTC  succeeded\n"
            . "maintain  enabled  Thu 2026-10-15 02:30:00 UTC  -                            never ran\n"
            . "drill     enabled  Thu 2026-10-15 02:30:00 UTC  -                            never ran\n",
            Artisan::output(),
        );
        self::assertStringNotContainsString('warning', $this->logOutput());
    }

    public function testStatusOfAFailedAndAMissingTimerIsExitOne(): void
    {
        $this->units->properties['arkhive-backup.timer'] = ['LoadState' => 'loaded', 'UnitFileState' => 'enabled', 'ActiveState' => 'active', 'NextElapseUSecRealtime' => 'Thu 2026-10-15 02:30:00 UTC', 'LastTriggerUSec' => 'Wed 2026-10-14 02:31:12 UTC'];
        $this->units->properties['arkhive-backup.service'] = ['Result' => 'exit-code', 'ExecMainCode' => '1', 'ExecMainStatus' => '69', 'ExecMainStartTimestamp' => 'Wed 2026-10-14 02:31:12 UTC', 'ExecMainExitTimestamp' => 'Wed 2026-10-14 02:31:40 UTC'];
        $this->units->properties['arkhive-maintain.timer'] = ['LoadState' => 'loaded', 'UnitFileState' => 'disabled', 'ActiveState' => 'inactive', 'NextElapseUSecRealtime' => '', 'LastTriggerUSec' => ''];

        self::assertSame(ExitCode::FAILURE, Artisan::call('schedule', ['--status' => true, '--json' => true]), $this->logOutput());

        $json = json_decode(Artisan::output(), true, flags: JSON_THROW_ON_ERROR);
        self::assertIsArray($json);
        self::assertFalse($json['healthy']);
        self::assertSame(['backup', 'maintain', 'drill'], array_column($json['timers'], 'job'));
        self::assertSame([false, false, false], array_column($json['timers'], 'healthy'));
        self::assertSame([true, true, false], array_column($json['timers'], 'installed'));
        self::assertSame(['exit-code', null, null], array_column($json['timers'], 'last_result'));
        self::assertSame([69, null, null], array_column($json['timers'], 'last_exit_status'));
        self::assertStringContainsString('warning The last backup failed: see journalctl -u arkhive-backup.service', $this->logOutput());
        self::assertStringContainsString('warning arkhive-maintain.timer is disabled, inactive: enable it with systemctl enable --now arkhive-maintain.timer', $this->logOutput());
        self::assertStringContainsString('warning arkhive-drill.timer is not installed: run arkhive schedule --install', $this->logOutput());
    }

    public function testStatusTakesNoFormat(): void
    {
        self::assertSame(ExitCode::USAGE, Artisan::call('schedule', ['--status' => true, '--systemd' => true]));
        self::assertStringContainsString('error --status only reads the timers: it takes no --install, --systemd or --cron', $this->logOutput());
    }

    public function testSystemdUnitsForTheConfiguration(): void
    {
        $config = $this->writeConfig();

        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => $config, '--systemd' => true]), $this->logOutput());

        $output = Artisan::output();
        self::assertStringStartsWith("# ==> /etc/systemd/system/arkhive-backup.service <==\n# Generated by arkhive schedule for {$config}\n[Unit]\n", $output);
        self::assertStringContainsString("User=root\nExecStart=/usr/local/bin/arkhive backup --config {$config}\n", $output);
        self::assertStringContainsString("# ==> /etc/systemd/system/arkhive-drill.timer <==\n", $output);
        self::assertStringContainsString("ProtectHome=read-only\nReadWritePaths=-/srv/restic-repo\n", $output, 'the local repository stays writable');
        self::assertStringContainsString("OnCalendar=*-*-* 02:30:00\n", $output);
        self::assertStringEndsWith(
            "# Save each unit above under its path, then enable the timers:\n"
            . "#   systemctl daemon-reload\n"
            . "#   systemctl enable --now arkhive-backup.timer arkhive-maintain.timer arkhive-drill.timer\n"
            . "# Check with: systemctl list-timers 'arkhive-*' and journalctl -u arkhive-backup.service\n",
            $output,
        );
        self::assertFileDoesNotExist('/etc/systemd/system/arkhive-backup.service', 'nothing is installed');
    }

    public function testTheDumpDirectoryStaysWritable(): void
    {
        $config = $this->writeConfig(['RESTIC_REPOSITORY' => 'sftp:backup-user@backup.example.com:/restic', 'WITH_MYSQL' => 'true', 'MYSQL_HOST' => 'localhost', 'MYSQL_USER' => 'backup', 'MYSQL_PASSWORD' => 'mysql-password-placeholder', 'MYSQL_DATABASES' => 'shop', 'DUMP_DIRECTORY' => '/home/backup/dumps']);

        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => $config, '--systemd' => true]), $this->logOutput());
        self::assertStringContainsString("ReadWritePaths=-/home/backup/dumps\n", Artisan::output());
    }

    public function testCronLinesAtAnotherTime(): void
    {
        $config = $this->writeConfig();

        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => $config, '--cron' => true, '--at' => '23:40']));

        self::assertSame(
            "# Generated by arkhive schedule for {$config}\n"
            . "# Save as /etc/cron.d/arkhive (root:root, mode 0644). Logs: /var/log/arkhive.log\n"
            . "PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin\n"
            . "40 23 * * * root nice -n 10 /usr/local/bin/arkhive backup --config {$config} --log-file /var/log/arkhive.log >/dev/null 2>&1\n"
            . "40 2 * * 0 root nice -n 10 /usr/local/bin/arkhive maintain --config {$config} --log-file /var/log/arkhive.log >/dev/null 2>&1\n"
            . "40 2 * * 3 root nice -n 10 /usr/local/bin/arkhive drill --config {$config} --log-file /var/log/arkhive.log >/dev/null 2>&1\n",
            Artisan::output(),
        );
        self::assertStringNotContainsString('mkdir', $this->logOutput());
    }

    public function testAnotherUserLogsUnderTheStateDirectory(): void
    {
        ScheduleCommand::$user = 'deploy';
        $this->terminal->env = ['HOME' => '/home/deploy'];

        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => $this->writeConfig(), '--cron' => true]));

        self::assertStringContainsString("# Add to the crontab of deploy with: crontab -e. Logs: /home/deploy/.local/state/arkhive/arkhive.log\n", Artisan::output());
        self::assertStringContainsString("notice Create the log directory first: mkdir -p '/home/deploy/.local/state/arkhive'", $this->logOutput());

        $this->terminal->env = ['HOME' => '/home/deploy', 'XDG_STATE_HOME' => '/srv/state'];
        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => $this->writeConfig(), '--cron' => true]));
        self::assertStringContainsString('--log-file /srv/state/arkhive/arkhive.log ', Artisan::output());

        // a relative XDG_STATE_HOME is invalid by the XDG specification: ignored
        $this->terminal->env = ['HOME' => '/home/deploy', 'XDG_STATE_HOME' => 'state'];
        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => $this->writeConfig(), '--systemd' => true]));
        self::assertStringContainsString("User=deploy\n", Artisan::output());
    }

    public function testWithoutNotificationsItWarns(): void
    {
        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => $this->writeConfig(), '--cron' => true]));
        self::assertStringContainsString('warning No notifications are configured: a scheduled run that fails would go unnoticed. Set NOTIFY=true, NOTIFY_ON=failure and the SMTP keys, or monitor with: arkhive status --max-age 26', $this->logOutput());
    }

    public function testWithNotificationsItDoesNotWarn(): void
    {
        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => $this->writeConfig(self::notify('failure')), '--cron' => true]));
        self::assertStringNotContainsString('No notifications', $this->logOutput());
    }

    public function testUnattendedWithoutAFormatIsExitTwoNamingTheFlags(): void
    {
        $prompter = new FakePrompter([]);
        $this->app->instance(Prompter::class, $prompter);

        self::assertSame(ExitCode::USAGE, Artisan::call('schedule', ['--config' => $this->writeConfig()]));

        self::assertStringContainsString('error The scheduler is required in unattended mode: pass --systemd or --cron', $this->logOutput());
        self::assertSame('', Artisan::output());
        self::assertSame([], $prompter->questions);
    }

    public function testInATerminalItAsksWithSystemdOrCronAsTheDefault(): void
    {
        $this->terminal->stdinTty = true;
        $this->terminal->stdoutTty = true;
        $prompter = new FakePrompter(['']);
        $this->app->instance(Prompter::class, $prompter);

        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => $this->writeConfig()]));
        self::assertSame(['Schedule with'], $prompter->questions);
        self::assertStringContainsString('[Timer]', Artisan::output());

        ScheduleCommand::$systemd = false;
        $prompter = new FakePrompter(['']);
        $this->app->instance(Prompter::class, $prompter);
        self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => $this->writeConfig()]));
        self::assertStringContainsString('PATH=/usr/local/sbin', Artisan::output());
    }

    public function testBothFormatsAreAUsageError(): void
    {
        self::assertSame(ExitCode::USAGE, Artisan::call('schedule', ['--config' => $this->writeConfig(), '--systemd' => true, '--cron' => true]));
        self::assertStringContainsString('error --systemd and --cron are alternatives: pass one of them', $this->logOutput());
    }

    public function testABadTimeIsAUsageError(): void
    {
        self::assertSame(ExitCode::USAGE, Artisan::call('schedule', ['--config' => $this->writeConfig(), '--cron' => true, '--at' => '25:00']));
        self::assertStringContainsString("error --at must be a time of day as HH:MM (24 h), not '25:00'", $this->logOutput());
        self::assertStringContainsString('notice For example: arkhive schedule --systemd --at 02:30', $this->logOutput());
    }

    public function testAnInvalidConfigurationIsNotScheduled(): void
    {
        $config = $this->writeConfig();
        chmod("{$this->dir}/password", 0644);

        self::assertSame(ExitCode::CONFIG, Artisan::call('schedule', ['--config' => $config, '--cron' => true]));
        self::assertSame('', Artisan::output());
    }

    public function testTheConfigPathIsMadeAbsolute(): void
    {
        $this->writeConfig();
        $cwd = (string) getcwd();
        chdir($this->dir);
        try {
            self::assertSame(ExitCode::SUCCESS, Artisan::call('schedule', ['--config' => 'config', '--cron' => true]));
        } finally {
            chdir($cwd);
        }

        self::assertStringContainsString('backup --config ' . realpath("{$this->dir}/config") . ' ', Artisan::output());
    }

    /**
     * The real process: under a pseudo-TTY the question is asked on stderr and answered on stdin;
     * without a TTY it is exit 2. From source the schedule calls PHP on the entry point.
     */
    public function testTheRealCommandInBothModes(): void
    {
        $config = $this->writeConfig();

        $unattended = Cli::run(['schedule', '--config', $config]);
        self::assertSame(ExitCode::USAGE, $unattended->exitCode, $unattended->output());
        self::assertStringContainsString('pass --systemd or --cron', $unattended->stderr);

        $interactive = Cli::run(['schedule', '--config', $config], pty: true, stdin: "2\n");
        self::assertSame(ExitCode::SUCCESS, $interactive->exitCode, $interactive->output());
        self::assertStringContainsString('Schedule with', $interactive->stdout);
        self::assertStringContainsString(PHP_BINARY . ' ' . dirname(__DIR__, 2) . "/arkhive backup --config {$config} --log-file ", $interactive->stdout);
    }
}
